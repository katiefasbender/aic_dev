@dataclass
class ATLASRefcat2Meta:
    """Container for ATLAS-Refcat2 metadata.
    """

    name: str = "atlas"
    fullname: str = "ATLAS-Refcat2"
    default_path = "/net/scratch/kmfas/atlas_refcat2/atlas" # on Aurora server
    col_map: dict[str, ColumnInfo] = field(default_factory=dict) 
    default_filters: list = [["g", "<=", 19.0], ["dec", ">=", -20.0]]
    id_and_coords_map: dict[str,str] = {"id": "Unnamed: 0", "ra": "ra", "dec": "dec"} # ID is not correct, this is a placeholder

    @classmethod # rename to build_colmap?
    def from_defaults(cls,extra_col_names: list[str] | None = None) -> "ATLASRefcat2Meta":
        '''Create class instance with default columns, and additional columns if specified'''
        merged = {name: spec for name, spec in ATLAS_COLUMNS.items() if spec.is_default}
        if extra_col_names:
            for name in extra_col_names:
                merged[name] = ATLAS_COLUMNS[name]
        return cls(col_map=merged)


    def columns_to_open(self) -> list[str]:
        '''Return a list of original column names to call when opening/loading catalog with lsdb.open_catalog()'''
        return [name for name, spec in self.col_map.items()]


@dataclass
class ATLASRefcat2:
    """Container for ATLAS-Refcat2 Catalog & metadata.

    Attributes
    ----------
    path (str) Full path to HATSed catalog (location on-disk or URL through data.lsdb.io)
    columns (list[str]) List of column names to load; input for lsdb.open_catalog() (expect elements [0,1,2] to be [ID,RA,Dec] column names)
    filters (list[tuple]) List of filters on rows; input for lsdb.open_catalog()
    catalog (lsdb.Catalog) Lazily-loaded catalog in HATs format; opened with lsdb.open_catalog()
    dask_meta (pandas.DataFrame) meta information for catalog column names and dtypes; input for map_partitions()

    Example:
    --------
    >>> atlas = ATLASRefcat2(path="/path/to/atlas",columns=["id","ra","dec","g"],filters=[["dec",">",-20.0],["g","<",19.0]])
    """

    metadata: ATLASRefcat2Meta
    data: lsdb.Catalog

    def __init__(
        self,
        path: str,
        columns: list = None,
        filters: list = None,
        catalog: lsdb.Catalog = None,
        dask_meta: pd.DataFrame = None,
    ):
        self.path = path
        if columns is not None:
            self.columns = columns
        else:
            self.columns = [
                "Unnamed: 0",
                "ra",
                "dec",
                "parallax",
                "pmra",
                "pmdec",
                "g",
                "r",
                "i",
                "h32",
                "h64",
                "h256",
            ]
        if filters is not None:
            self.filters = filters
        else:
            self.filters = [["g", "<=", 19.0], ["r", "<=", 19.0], ["i", "<=", 19.0], ["dec", ">=", -20.0]]
        self.catalog = catalog
        self.dask_meta = dask_meta

    @classmethod
    def open(cls,path):
        cat = lsdb.open_catalog(path)
        return cls(path=path,catalog=cat)


